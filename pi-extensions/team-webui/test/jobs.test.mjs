import test,{after} from "node:test";
import assert from "node:assert/strict";
import {mkdtemp,rm} from "node:fs/promises";
import {tmpdir,homedir} from "node:os";
import {join} from "node:path";
import {createHash} from "node:crypto";
import {createRequire} from "node:module";
import {createBackgroundJobs} from "../jobs.ts";
const root=await mkdtemp(join(tmpdir(),"pi-jobs-web-test-"));
process.env.PI_CODING_AGENT_DIR=join(root,"profile");
after(()=>rm(root,{recursive:true,force:true}));
const {createHub}=await import("../hub.ts");
const {keyFor}=await import("../registry.ts");
const manager=createRequire(import.meta.url)("../../background-bash/manager.cjs");
const wait=ms=>new Promise(done=>setTimeout(done,ms));
const until=async fn=>{for(let i=0;i<100;i++){const value=fn();if(value)return value;await wait(50);}throw Error("Timed out");};
test("background jobs work after Pi disconnects and read/stop/download stay scoped to the authenticated session",async t=>{
 const jobRoot=join(root,"jobs"),session="owner-a",other="owner-b",dir=join(jobRoot,createHash("sha256").update(session).digest("hex").slice(0,24));
 const job=await manager.start(dir,{command:"printf '\\033]52;c;bad\\007safe job log\\n'; sleep 30",cwd:root,notify:false,env:{...process.env,PRIVATE_JOB_SECRET:"not-public"}});
 t.after(async()=>{manager.stop(dir,job.id);await until(()=>manager.read(dir,job.id).finishedAt);});
 await until(()=>manager.tail(dir,job.id).includes("safe job log"));
 const service=createBackgroundJobs({root:jobRoot,manager});
 const catalog=[session,other].map(id=>({id,key:keyFor(id),project:"Fixture",cwd:root,root,online:false}));
 const hub=await createHub({port:0,token:"jobs-test",history:async()=>[],registry:async()=>catalog,members:async()=>new Map(),jobsService:service});t.after(()=>hub.stop());
 const base=hub.urls[0];
 const login=await fetch(base+"/api/login",{method:"POST",headers:{"Content-Type":"application/json",Origin:base},body:JSON.stringify({name:"Tester",token:hub.token})});
 const cookie=login.headers.get("set-cookie").split(";")[0];
 const url=(id,action)=>base+"/api/sessions/"+keyFor(id)+"/"+action;
 const post=(id,action,body)=>fetch(url(id,action),{method:"POST",headers:{"Content-Type":"application/json",Origin:base,Cookie:cookie},body:JSON.stringify(body)});
 assert.equal((await fetch(url(session,"jobs"))).status,401);
 const own=await(await fetch(url(session,"jobs"),{headers:{Cookie:cookie}})).json();
 assert.equal(own.jobs.length,1);assert.equal(own.detail.id,job.id);
 assert.ok(own.detail.output.includes("safe job log"));assert.ok(!own.detail.output.includes("52;c;"));
 assert.ok(!JSON.stringify(own).includes("PRIVATE_JOB_SECRET"));
 assert.equal((await(await fetch(url(session,"jobs?summary=1"),{headers:{Cookie:cookie}})).json()).detail,null);
 assert.equal((await fetch(url(other,"jobs?id="+job.id),{headers:{Cookie:cookie}})).status,404);
 assert.equal((await post(other,"job-stop",{id:job.id})).status,404);
 assert.equal(manager.read(dir,job.id).status,"running");
 assert.equal((await post(session,"job-stop",{id:"../escape"})).status,400);
 const download=await fetch(url(session,"jobs?id="+job.id+"&download=1"),{headers:{Cookie:cookie}});
 assert.equal(download.status,200);assert.match(download.headers.get("content-disposition"),/attachment/);
 assert.ok((await download.text()).includes("safe job log"));
 const stopped=await post(session,"job-stop",{id:job.id});assert.equal(stopped.status,200);assert.equal((await stopped.json()).status,"stop_requested");
 await until(()=>manager.read(dir,job.id).finishedAt);
 assert.equal(service.snapshot(session,job.id).detail.status,"stopped");
 assert.equal(service.snapshot(session).jobs.length,1,"finished jobs remain available in history");
 assert.equal(service.snapshot(other).jobs.length,0);
});
