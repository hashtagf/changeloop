import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, rmSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { homedir, tmpdir } from 'node:os';
import { describe, git } from '../workspace.ts';
import { createTaskStore } from '../task-store.ts';

test('installed Pi loads task tools and restores project work in a fresh session and worktree', async t => {
  const temp=mkdtempSync(join(tmpdir(),'pi-task-sdk-')),previous=process.env.PI_TASKS_ROOT;
  process.env.PI_TASKS_ROOT=join(temp,'db');
  const previousProfile=process.env.PI_CODING_AGENT_DIR;process.env.PI_CODING_AGENT_DIR=join(temp,'profile');
  t.after(()=>{if(previousProfile===undefined)delete process.env.PI_CODING_AGENT_DIR;else process.env.PI_CODING_AGENT_DIR=previousProfile;});
  mkdirSync(join(temp,'profile/web-ui/sessions'),{recursive:true});
  writeFileSync(join(temp,'profile/web-ui/sessions','a'.repeat(32)+'.json'),JSON.stringify({id:'recipient',cwd:temp,root:temp,projectRoot:temp,sessionName:'Existing reviewer',pid:process.pid,updated:Date.now()}));
  t.after(()=>{if(previous===undefined)delete process.env.PI_TASKS_ROOT;else process.env.PI_TASKS_ROOT=previous;rmSync(temp,{recursive:true,force:true});});
  await git(temp,['init']);await git(temp,['-c','user.name=Test','-c','user.email=test@example.invalid','commit','--allow-empty','-m','fixture']);
  const alternate=join(temp,'worktree');await git(temp,['worktree','add','--detach',alternate]);
  const version=readFileSync(join(homedir(),'.pi/agent/install/current-version'),'utf8').trim();
  const base=join(homedir(),`.pi/agent/install/releases/${version}/node_modules/@earendil-works/pi-coding-agent`);
  const {loadExtensions,createExtensionRuntime}=await import(join(base,'dist/core/extensions/loader.js'));
  const loaded=await loadExtensions([new URL('../extension.ts',import.meta.url).pathname],temp,undefined,createExtensionRuntime());
  assert.deepEqual(loaded.errors,[]);
  const ext=loaded.extensions[0],tool=ext.tools.get('task_board'),execute=(tool.definition||tool).execute;
  const context=(id,cwd)=>({cwd,sessionManager:{getSessionId:()=>id,getSessionName:()=>id}});
  const created=await execute('c1',{action:'create',key:'task',title:'Carry this across sessions',nextStep:'Implement regression'},undefined,undefined,context('first',temp));
  const result=await execute('c2',{action:'list'},undefined,undefined,context('second',alternate));
  assert.equal(result.details.tasks[0].id,created.details.task.id);
  assert.equal(result.details.tasks[0].ownerSessionId,'first');
  const before=ext.handlers.get('before_agent_start');let prompts=[];
  for(const fn of before)prompts.push((await fn({systemPrompt:'Existing policy'},context('second',alternate)))?.systemPrompt);
  assert.ok(prompts.some(p=>p.includes('projectActive')));
  assert.ok(prompts.every(p=>!p?.includes('Carry this across sessions')),'unassigned tasks must not inflate another session prompt');
  const ownPrompts=[];for(const fn of before)ownPrompts.push((await fn({systemPrompt:'Existing policy'},context('first',temp)))?.systemPrompt);
  assert.ok(ownPrompts.some(p=>p.includes('Carry this across sessions')&&p.includes('Implement regression')));

  assert.equal(createTaskStore().list((await describe(alternate)).projectRoot).total,1);
  mkdirSync(join(temp,'.foundation/runtime'),{recursive:true});
  writeFileSync(join(temp,'.foundation/runtime/example.json'),JSON.stringify({id:'example',status:'building',intent:'Linked SDK change'}));
  const linked=await execute('link',{action:'link',id:created.details.task.id,changeId:'example'},undefined,undefined,context('second',alternate));
  assert.equal(linked.details.task.workflow.phase,'build');
  const synced=await execute('sync',{action:'sync'},undefined,undefined,context('second',alternate));
  assert.equal(synced.details.total,1);assert.equal(synced.details.tasks[0].id,created.details.task.id);
  const agents=await execute('agents',{action:'agents'},undefined,undefined,context('second',temp));assert.equal(agents.details.agents[0].id,'recipient');
  for(const [suffix,id,pid] of [['b','zzz-online',process.pid],['c','zzz-offline',2147483647]]) {
    writeFileSync(join(temp,'profile/web-ui/sessions',suffix.repeat(32)+'.json'),JSON.stringify({id,cwd:temp,root:temp,projectRoot:temp,sessionName:id,pid,sessionFile:join(temp,'saved.jsonl'),updated:Date.now()}));
  }
  const firstPage=await execute('page1',{action:'agents',limit:1},undefined,undefined,context('second',temp));
  assert.equal(firstPage.details.agents.length,1);assert.equal(firstPage.details.nextOffset,1);
  const secondPage=await execute('page2',{action:'agents',limit:1,offset:1},undefined,undefined,context('second',temp));
  assert.equal(secondPage.details.agents[0].id,'zzz-online');assert.equal(secondPage.details.nextOffset,null);
  const offline=await execute('all',{action:'agents',includeInactive:true},undefined,undefined,context('second',temp));
  assert.ok(offline.details.agents.some(a=>a.id==='zzz-offline'));
  const handoff=await execute('handoff',{action:'handoff',id:linked.details.task.id,version:linked.details.task.version,ownerSessionId:'recipient',nextStep:'Review and save findings on this task'},undefined,undefined,context('second',temp));
  assert.equal(handoff.details.task.ownerSessionId,'recipient');
  const inbox=await execute('inbox',{action:'inbox'},undefined,undefined,context('recipient',alternate));assert.equal(inbox.details.tasks[0].id,linked.details.task.id);
  const graph=await execute('graph',{action:'graph',project:temp},undefined,undefined,context('recipient',alternate));assert.equal(graph.details.nodes.length,1);
  const plan=await execute('plan',{action:'plan',ownerSessionId:'recipient',limit:1},undefined,undefined,context('recipient',alternate));
  assert.equal(plan.details.topology,'single');assert.equal(plan.details.counts.ready,1);
  assert.equal(plan.details.tasks[0].id,handoff.details.task.id);
  assert.equal(plan.details.execution,'advisory-only');
  const brief=await execute('brief',{action:'brief',id:handoff.details.task.id},undefined,undefined,context('recipient',alternate));
  assert.equal(brief.details.project,(await describe(alternate)).projectRoot);
  assert.equal(brief.details.ownerSessionId,'recipient');
  assert.equal(brief.details.nextStep,'Review and save findings on this task');
  assert.equal(brief.details.version,handoff.details.task.version);
  const guide=ext.tools.get('tool_guide');assert.ok(guide);
  const readGuide=(guide.definition||guide).execute;
  const topic=await readGuide('guide',{topic:'tasks'});assert.ok(topic.details.how.some(e=>e.action==='delete'));
  assert.ok(topic.details.how.some(e=>e.action==='plan'));
  assert.ok(topic.details.how.some(e=>e.action==='brief'));
  assert.ok(JSON.stringify(topic).length<6000);
  await assert.rejects(()=>readGuide('guide',{topic:'invalid'}),/Unknown/);
  const deleted=await execute('del',{action:'delete',id:handoff.details.task.id,version:handoff.details.task.version},undefined,undefined,context('recipient',temp));
  const trash=await execute('trash',{action:'list',deleted:true},undefined,undefined,context('recipient',temp));assert.equal(trash.details.total,1);
  const normal=await execute('normal',{action:'list'},undefined,undefined,context('recipient',temp));assert.equal(normal.details.total,0);
  const restored=await execute('restore',{action:'restore',id:deleted.details.task.id,version:deleted.details.task.version},undefined,undefined,context('recipient',temp));assert.equal(restored.details.task.deletedAt,undefined);

});
