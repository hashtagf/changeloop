from playwright.sync_api import sync_playwright,expect
from pathlib import Path
import json,sys
out=Path(__file__).resolve().parent.parent/'reports'
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/Applications/Google Chrome.app/Contents/MacOS/Google Chrome')
 page=browser.new_page(viewport={'width':1280,'height':800});page.set_default_timeout(15000)
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(sys.argv[1]+'/#preview-only');page.locator('#name').fill('Task Tester');page.locator('#login-form button').click()
 page.locator('#view-tasks').click();expect(page.locator('.task-column')).to_have_count(10)
 expect(page.locator('#task-add')).to_be_enabled()
 first=page.locator('#task-project').input_value()
 page.locator('#task-add').click()
 page.locator('[name=title]').fill('Keep work across sessions')
 page.locator('[name=status]').select_option('investigate')
 page.locator('[name=nextStep]').fill('Implement and verify the session handoff')
 page.locator('[name=blocker]').fill('Waiting for design review')
 page.locator('#task-save').click();expect(page.locator('#task-dialog')).not_to_be_visible()
 expect(page.locator('[data-status=plan] .task-card')).to_have_count(1)
 card=page.locator('.task-card').filter(has_text='Keep work across sessions');card.click()
 page.locator('[name=status]').select_option('deploy');page.locator('#task-save').click()
 expect(page.locator('#task-edit-error')).to_contain_text('evidence')
 page.locator('[name=status]').select_option('build');page.locator('#task-save').click()
 expect(page.locator('[data-status=build] .task-card')).to_have_count(1)
 # Concurrent agent edit must not be overwritten by the stale user draft.
 card.click();page.locator('[name=nextStep]').fill('My unsaved next step')
 result=page.request.get(sys.argv[1]+'/api/tasks',params={'project':first}).json();task=next(t for t in result['tasks'] if t['title']=='Keep work across sessions')
 response=page.request.post(sys.argv[1]+'/api/tasks',headers={'Origin':sys.argv[1]},data={'action':'update','project':first,'id':task['id'],'version':task['version'],'blocker':'Changed by another session'})
 assert response.status==200,response.text()
 page.locator('#task-save').click();expect(page.locator('#task-edit-error')).to_contain_text('another session')
 expect(page.locator('[name=nextStep]')).to_have_value('My unsaved next step')
 page.once('dialog',lambda d:d.accept());page.locator('#task-reload').click()
 expect(page.locator('[name=blocker]')).to_have_value('Changed by another session')
 page.locator('#task-close').click()
 # Drag-to-move has the same version checks as form-based movement.
 page.locator('#task-refresh').click();expect(card).to_contain_text('Changed by another session')
 card.drag_to(page.locator('[data-status=design] .task-column-head'))
 expect(page.locator('[data-status=design] .task-card')).to_have_count(1)
 page.reload();expect(page.locator('#task-board')).to_be_visible();expect(page.locator('[data-status=design] .task-card')).to_have_count(1)
 page.locator('#task-search').fill('no matching task');expect(page.locator('.task-card')).to_have_count(0)
 page.locator('#task-search').fill('');expect(page.locator('.task-card')).to_have_count(1)
 options=page.locator('#task-project option').evaluate_all('(items)=>items.map(n=>n.value)')
 other=next(value for value in options if value!=first)
 page.locator('#task-project').select_option(other);expect(page.locator('.task-card')).to_have_count(0)
 page.locator('#task-project').select_option(first);expect(page.locator('.task-card')).to_have_count(1)
 page.screenshot(path=str(out/'tasks-desktop.png'))
 page.set_viewport_size({'width':390,'height':844});page.locator('#task-filter').select_option('change')
 expect(page.locator('.task-column')).to_have_count(1)
 assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
 page.screenshot(path=str(out/'tasks-mobile.png'))
 card.click();expect(page.locator('#task-dialog')).to_be_visible()
 expect(page.locator('[name=status]')).to_have_value('change')
 expect(page.locator('#task-edit-error')).to_be_empty()
 assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
 page.screenshot(path=str(out/'tasks-detail-mobile.png'))
 page.locator('#task-close').click();page.locator('#view-chat').click();expect(page.locator('#task-board')).not_to_be_visible()
 assert not errors,errors
 report={'passed':True,'checks':['10 requested columns','create','required evidence','edit','concurrent version conflict preserves draft','reload latest','drag status change','page reload persistence','search','project isolation','mobile board and detail','return to chat'],'page_errors':errors,'model_requests':0}
 (out/'tasks-browser.json').write_text(json.dumps(report,indent=2));print(json.dumps(report),flush=True)
 page.close();browser.close()
