#!/usr/bin/env node
// Generates docs/tools.md from what each extension actually registers when Pi's
// own loader runs it: tools (description and parameter schema), commands and
// shortcuts. `--check` fails when the committed file is stale; `--write` updates it.
import { mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const DOC = join(root, 'docs', 'tools.md');

const oneLine = text => String(text ?? '').replace(/\s+/g, ' ').trim();
const cell = text => oneLine(text).replace(/\|/g, '\\|');

export function typeOf(schema) {
  if (!schema || typeof schema !== 'object') return 'any';
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (Array.isArray(schema.enum)) return schema.enum.map(v => JSON.stringify(v)).join(' \\| ');
  const union = schema.anyOf || schema.oneOf;
  if (Array.isArray(union)) return union.map(typeOf).join(' \\| ');
  if (schema.type === 'array') {
    const item = typeOf(schema.items);
    return `${item.includes(' \\| ') ? `(${item})` : item}[]`;
  }
  if (schema.type === 'object' && schema.properties) return `{ ${Object.keys(schema.properties).join(', ')} }`;
  return Array.isArray(schema.type) ? schema.type.join(' \\| ') : schema.type || 'any';
}

function limits(schema) {
  const parts = [];
  for (const [key, label] of [['minLength', 'min length'], ['maxLength', 'max length'], ['minimum', 'min'], ['maximum', 'max'], ['minItems', 'min items'], ['maxItems', 'max items']]) {
    if (schema?.[key] !== undefined) parts.push(`${label} ${schema[key]}`);
  }
  return parts.join(', ');
}

export function renderTool(definition) {
  const lines = [`### \`${definition.name}\``, '', oneLine(definition.description), ''];
  const params = definition.parameters;
  const props = params?.properties || {};
  const required = new Set(params?.required || []);
  if (Object.keys(props).length) {
    lines.push('| Parameter | Type | Required | Notes |', '|---|---|---|---|');
    for (const [name, schema] of Object.entries(props)) {
      const notes = [oneLine(schema?.description), limits(schema)].filter(Boolean).join('; ');
      lines.push(`| \`${name}\` | ${typeOf(schema)} | ${required.has(name) ? 'yes' : 'no'} | ${cell(notes)} |`);
    }
  } else lines.push('No parameters.');
  lines.push('', '<details><summary>JSON schema</summary>', '', '```json', JSON.stringify(params ?? {}, null, 2), '```', '', '</details>', '');
  return lines.join('\n');
}

export function render(extensions) {
  const out = ['# Tool reference', '', '<!-- Generated by scripts/tool-docs.mjs from the registered tools. Do not edit; run `npm run docs`. -->', ''];
  for (const { name, tools, commands, shortcuts } of extensions) {
    out.push(`## ${name}`, '');
    if (commands.length) {
      out.push('**Commands**', '', '| Command | Description |', '|---|---|', ...commands.map(c => `| \`/${c.name}\` | ${cell(c.description)} |`), '');
    }
    if (shortcuts.length) {
      out.push('**Shortcuts**', '', '| Key | Description |', '|---|---|', ...shortcuts.map(s => `| \`${s.shortcut}\` | ${cell(s.description)} |`), '');
    }
    for (const tool of tools) out.push(renderTool(tool));
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

export async function collect() {
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  const loaderPath = join(root, 'node_modules', '@earendil-works', 'pi-coding-agent', 'dist', 'core', 'extensions', 'loader.js');
  if (!existsSync(loaderPath)) throw new Error('Run npm install in pi-extensions first (devDependencies provide the Pi loader).');
  // Isolate every state/config root so the output depends only on the source.
  const scratch = mkdtempSync(join(tmpdir(), 'pi-ext-docs-'));
  const saved = {};
  const env = { HOME: scratch, XDG_CONFIG_HOME: join(scratch, 'config'), PI_CODING_AGENT_DIR: join(scratch, 'agent'), PI_TEAM_ROOT: join(scratch, 'team'), PI_QUESTIONS_ROOT: join(scratch, 'questions') };
  for (const [key, value] of Object.entries(env)) { saved[key] = process.env[key]; process.env[key] = value; }
  try {
    const { loadExtensions, createExtensionRuntime } = await import(loaderPath);
    const loaded = await loadExtensions(pkg.pi.extensions.map(entry => resolve(root, entry)), root, undefined, createExtensionRuntime());
    if (loaded.errors.length) throw new Error(`Extensions failed to load: ${JSON.stringify(loaded.errors)}`);
    return loaded.extensions.map((extension, index) => ({
      name: pkg.pi.extensions[index].replace(/^\.\//, '').replace(/\/index\.ts$/, ''),
      tools: [...extension.tools.values()].map(tool => tool.definition || tool),
      commands: [...extension.commands.values()].map(c => ({ name: c.name, description: c.description })),
      shortcuts: [...extension.shortcuts.values()].map(s => ({ shortcut: s.shortcut, description: s.description })),
    }));
  } finally {
    for (const [key, value] of Object.entries(saved)) { if (value === undefined) delete process.env[key]; else process.env[key] = value; }
    rmSync(scratch, { recursive: true, force: true });
  }
}

export function compare(expected, actual) {
  return expected === actual ? [] : ['docs/tools.md is out of date with the registered tools; run `npm run docs` (in pi-extensions) and commit the result.'];
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2];
  if (!['--check', '--write'].includes(mode)) { console.error('usage: tool-docs.mjs --check | --write'); process.exit(2); }
  const generated = render(await collect());
  if (mode === '--write') { writeFileSync(DOC, generated); console.log(`✓ wrote ${DOC}`); process.exit(0); }
  const problems = compare(generated, existsSync(DOC) ? readFileSync(DOC, 'utf8') : '');
  if (problems.length) { console.error(`✗ ${problems.join('\n')}`); process.exit(1); }
  console.log('✓ docs/tools.md matches the registered tools');
  process.exit(0); // extension timers must not keep the check alive
}
