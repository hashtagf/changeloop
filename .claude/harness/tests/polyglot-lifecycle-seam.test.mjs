function write(root, files) {
  for (const [name, text] of Object.entries(files)) {
    mkdirSync(dirname(join(root, name)), { recursive: true });
    writeFileSync(join(root, name), text);
  }
}

function consumer(language) {
  const spec = LANGUAGES[language];
  const temp = mkdtempSync(join(tmpdir(), `foundation-polyglot-${language}-`));
  const project = join(temp, "consumer");
  mkdirSync(project, { recursive: true });
  const run = (command, args) => execFileSync(command, args, {
    cwd: project, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"]
  }).trim();
  installConsumer(project, { sourceRoot });
  run("git", ["config", "user.email", "fixture@example.test"]);
  run("git", ["config", "user.name", "Fixture"]);
  const policyPath = join(project, "foundation.json");
  const policy = JSON.parse(readFileSync(policyPath, "utf8"));
  policy.workflow.grounding = "optional";
  writeFileSync(policyPath, `${JSON.stringify(policy, null, 2)}\n`);
  write(project, spec.seed);
  if (spec.gitignore) writeFileSync(join(project, ".gitignore"),
    `${existsSync(join(project, ".gitignore")) ? readFileSync(join(project, ".gitignore"), "utf8") : ""}${spec.gitignore}`);
  run("git", ["add", "-A"]);
  run("git", ["commit", "-qm", "seed"]);
  mkdirSync(join(project, ".foundation/drafts"), { recursive: true });
  writeFileSync(join(project, ".foundation/drafts/subtract.json"), JSON.stringify({
    intent: "Calc exports subtract that returns a minus b",
    requirements: [{ description: "The calc module SHALL export subtract(a, b) returning a minus b",
      scenarios: [{ when: "subtract(5, 3) is called", then: "it returns 2" }] }],
    tasks: [{ outcome: "Add subtract with a test", verify: spec.verify, paths: spec.paths }]
  }));
  const env = { ...process.env };
  delete env.NODE_TEST_CONTEXT;
  const cli = (...args) => spawnSync("node", [".claude/harness/foundation.mjs", ...args],
    { cwd: project, encoding: "utf8", env });
  const started = cli("start", ".foundation/drafts/subtract.json",
    "--approve-spec", "--decision-ref", "fixture://user/spec");
  assert.equal(started.status, 0, started.stderr || started.stdout);
  const id = started.stdout.match(/CREATED (\S+)/)?.[1];
  assert.ok(id, started.stdout);
  const build = cli("advance", id, "--through", "build");
  assert.match(build.stdout, /"action":"EDIT"/, build.stderr || build.stdout);
  const workspace = JSON.parse(readFileSync(join(project, ".foundation/runtime", `${id}.json`), "utf8")).workspace.path;
  return { temp, project, id, cli, workspace, spec };
}

for (const language of Object.keys(LANGUAGES)) {
  const { tool } = LANGUAGES[language];
  const skip = onPath(tool) ? false : `${tool} is not installed on this machine`;

  test(`a ${language} consumer reaches archived on its own test runner`, { skip }, () => {
    const fixture = consumer(language);
    try {
      write(fixture.workspace, fixture.spec.build(fixture.spec.correct));
      const landed = fixture.cli("advance", fixture.id, "--through", "archived");
      assert.equal(landed.status, 0, landed.stderr || landed.stdout);
      assert.match(landed.stdout, /"reached":"archived"/, landed.stderr || landed.stdout);
      const receipts = join(fixture.project, ".foundation/receipts", fixture.id);
      assert.equal(JSON.parse(readFileSync(join(receipts, "test.json"), "utf8")).status, "pass");
      // The language's own runner output is counted: both tests, not a bare exit code.
      const receipt = JSON.parse(readFileSync(join(receipts, "discovery.json"), "utf8"));
      assert.equal(receipt.status, "pass", receipt.observed);
      assert.match(String(receipt.observed), /^2 discovered; minimum 1/, `${language}: ${receipt.observed}`);
      assert.match(readFileSync(join(fixture.project, fixture.spec.landed), "utf8"), fixture.spec.marker);
    } finally {
      rmSync(fixture.temp, { recursive: true, force: true });
    }
  });
}

test("a failing go test keeps the change from archived", { skip: onPath("go") ? false : "go is not installed on this machine" }, () => {
  const fixture = consumer("go");
  try {
    write(fixture.workspace, fixture.spec.build(fixture.spec.wrong));
    const result = fixture.cli("advance", fixture.id, "--through", "archived");
    assert.doesNotMatch(result.stdout, /"reached":"archived"/);
    assert.doesNotMatch(readFileSync(join(fixture.project, "calc.go"), "utf8"), /Subtract/,
      "nothing landed");
  } finally {
    rmSync(fixture.temp, { recursive: true, force: true });
  }
});
